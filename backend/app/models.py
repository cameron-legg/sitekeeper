# Estimate
# ---------------------------------------------------------------------------


class Estimate(db.Model):
    __tablename__ = "estimates"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    job_id = Column(
        UUID(as_uuid=True),
        ForeignKey("jobs.id", ondelete="CASCADE"),
        nullable=False,
    )
    title = Column(String(255), nullable=False)
    delivered = Column(Boolean, nullable=False, default=False)
    # tax_rate is stored as a percentage (e.g. 8.5 = 8.5%). NULL = no tax.
    # Tax applies only to material entries, not hours.
    tax_rate = Column(Numeric(6, 4), nullable=True)
    created_at = Column(
        TIMESTAMP(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at = Column(
        TIMESTAMP(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )
    pdf_generated_at = Column(TIMESTAMP(timezone=True), nullable=True)
    pdf_object_key = Column(Text, nullable=True)

    job = relationship("Job", back_populates="estimates")
    line_items = relationship(
        "LineItem",
        primaryjoin="and_(LineItem.parent_id == Estimate.id, "
                    "LineItem.parent_type == 'estimate')",
        foreign_keys="LineItem.parent_id",
        cascade="all, delete-orphan",
        overlaps="line_items",
    )
    converted_invoice = relationship(
        "Invoice",
        back_populates="source_estimate",
        foreign_keys="Invoice.source_estimate_id",
    )

    def __repr__(self):
        return f"<Estimate {self.title}>"


