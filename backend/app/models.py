# ---------------------------------------------------------------------------
# LineItem  (v2 — named group with hourly_rate; price is derived)
# ---------------------------------------------------------------------------


class LineItem(db.Model):
    __tablename__ = "line_items"
    __table_args__ = (
        CheckConstraint(
            "parent_type IN ('estimate', 'invoice')",
            name="ck_line_items_parent_type",
        ),
    )

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    # parent_id references either estimates.id or invoices.id (no FK constraint
    # so it can be polymorphic); integrity enforced at the service layer.
    parent_id = Column(UUID(as_uuid=True), nullable=False)
    parent_type = Column(String(20), nullable=False)
    name = Column(String(255), nullable=False)
    notes = Column(Text, nullable=True)
    # hourly_rate is used by LineItemEntry rows of type 'hours'
    hourly_rate = Column(Numeric(12, 4), nullable=True)
    sort_order = Column(Integer, nullable=False, default=0)

    entries = relationship(
        "LineItemEntry",
        back_populates="line_item",
        cascade="all, delete-orphan",
        order_by="LineItemEntry.sort_order",
    )

    def __repr__(self):
        return f"<LineItem {self.name}>"


# ---------------------------------------------------------------------------
# LineItemEntry  (sub-item under a LineItem)
# ---------------------------------------------------------------------------


class LineItemEntry(db.Model):
    __tablename__ = "line_item_entries"
    __table_args__ = (
        CheckConstraint(
            "entry_type IN ('material', 'hours')",
            name="ck_line_item_entries_type",
        ),
    )

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    line_item_id = Column(
        UUID(as_uuid=True),
        ForeignKey("line_items.id", ondelete="CASCADE"),
        nullable=False,
    )
    entry_type = Column(String(20), nullable=False)  # 'material' | 'hours'
    name = Column(String(255), nullable=False)
    notes = Column(Text, nullable=True)
    url = Column(Text, nullable=True)

    # Material fields
    unit_price = Column(Numeric(12, 4), nullable=True)
    quantity = Column(Numeric(12, 4), nullable=True)

    # Hours fields
    hours = Column(Numeric(12, 4), nullable=True)

    sort_order = Column(Integer, nullable=False, default=0)

    line_item = relationship("LineItem", back_populates="entries")

    def __repr__(self):
        return f"<LineItemEntry [{self.entry_type}] {self.name}>"


