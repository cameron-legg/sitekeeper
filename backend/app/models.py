class BusinessInfo(db.Model):
    __tablename__ = "business_info"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    business_name = Column(String(255), nullable=True)
    state = Column(String(2), nullable=True)
    payment_method = Column(String(255), nullable=True)
    business_address = Column(String(500), nullable=True)
    business_phone = Column(String(50), nullable=True)
    business_email = Column(String(255), nullable=True)
    owner_user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    default_hourly_rate = Column(Numeric(12, 4), nullable=True)
    logo_object_key = Column(Text, nullable=True)
    updated_at = Column(
        TIMESTAMP(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    owner = relationship("User", foreign_keys=[owner_user_id])

    def __repr__(self):
        return f"<BusinessInfo {self.business_name}>"
