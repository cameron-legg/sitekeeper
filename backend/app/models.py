"""SQLAlchemy ORM models for the Contractor Management App.

All primary keys are UUID v4 (generated by PostgreSQL's gen_random_uuid()).
All timestamps use TIMESTAMPTZ so they are stored in UTC.
Cascade deletes are enforced at the database level via ON DELETE CASCADE.

Line item structure (v2):
  LineItem  — a named group (e.g. "Toilet Replacement") with an hourly_rate
    └── LineItemEntry  — either a material (type='material') or hours (type='hours')
        material: name, notes, url, unit_price, quantity  → total = unit_price * quantity
        hours:    name, notes, url, hours                 → cost  = hours * parent.hourly_rate

SavedItem mirrors LineItem and can have SavedItemEntry children.
"""

import uuid

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Column,
    Date,
    ForeignKey,
    Integer,
    Numeric,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func
from sqlalchemy.types import TIMESTAMP

from .extensions import db


