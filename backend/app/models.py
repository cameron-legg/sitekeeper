class JobSite(db.Model):
    __tablename__ = "job_sites"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )
    name = Column(String(255), nullable=False)
    description = Column(Text, nullable=True)
    address = Column(Text, nullable=True)
    primary_contact_id = Column(
        UUID(as_uuid=True),
        ForeignKey("contacts.id", ondelete="SET NULL"),
        nullable=True,
    )
    created_at = Column(
        TIMESTAMP(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at = Column(
        TIMESTAMP(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    user = relationship("User", back_populates="job_sites")
    primary_contact = relationship("Contact", foreign_keys=[primary_contact_id])
    contacts = relationship(
        "Contact", secondary=job_site_contacts, backref="job_sites"
    )
    jobs = relationship("Job", back_populates="job_site", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<JobSite {self.name}>"


