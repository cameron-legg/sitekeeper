"""SQLAlchemy ORM models for the Contractor Management App.

All primary keys are UUID v4 (generated by PostgreSQL's gen_random_uuid()).
All timestamps use TIMESTAMPTZ so they are stored in UTC.
Cascade deletes are enforced at the database level via ON DELETE CASCADE.

Line item structure (v2):
  LineItem  — a named group (e.g. "Toilet Replacement") with an hourly_rate
    └── LineItemEntry  — either a material (type='material') or hours (type='hours')
        material: name, notes, url, unit_price, quantity  → total = unit_price * quantity
        hours:    name, notes, url, hours                 → cost  = hours * parent.hourly_rate

SavedItem mirrors LineItem and can have SavedItemEntry children.
"""

import uuid

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Column,
    ForeignKey,
    Integer,
    Numeric,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func
from sqlalchemy.types import TIMESTAMP

from .extensions import db


# ---------------------------------------------------------------------------
# Association tables (many-to-many)
# ---------------------------------------------------------------------------

job_site_contacts = db.Table(
    "job_site_contacts",
    Column(
        "job_site_id",
        UUID(as_uuid=True),
        ForeignKey("job_sites.id", ondelete="CASCADE"),
        primary_key=True,
    ),
    Column(
        "contact_id",
        UUID(as_uuid=True),
        ForeignKey("contacts.id", ondelete="CASCADE"),
        primary_key=True,
    ),
)

job_contacts = db.Table(
    "job_contacts",
    Column(
        "job_id",
        UUID(as_uuid=True),
        ForeignKey("jobs.id", ondelete="CASCADE"),
        primary_key=True,
    ),
    Column(
        "contact_id",
        UUID(as_uuid=True),
        ForeignKey("contacts.id", ondelete="CASCADE"),
        primary_key=True,
    ),
)


# ---------------------------------------------------------------------------
# User
# ---------------------------------------------------------------------------


class User(db.Model):
    __tablename__ = "users"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    email = Column(String(255), nullable=False, unique=True)
    password_hash = Column(Text, nullable=False)
    name = Column(String(255), nullable=True)
    state = Column(String(2), nullable=True)
    company_name = Column(String(255), nullable=True)
    phone = Column(String(50), nullable=True)
    payment_method = Column(String(255), nullable=True)
    created_at = Column(
        TIMESTAMP(timezone=True), nullable=False, server_default=func.now()
    )

    job_sites = relationship(
        "JobSite", back_populates="user", cascade="all, delete-orphan"
    )
    saved_items = relationship(
        "SavedItem", back_populates="user", cascade="all, delete-orphan"
    )

    def __repr__(self):
        return f"<User {self.email}>"


